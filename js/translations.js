/**
 * Global Translation Helper with Dynamic Variable Interpolation & Missing-Key Detection
 */
window.herSpaceTranslate = function(key, vars, langOverride) {
  const lang = langOverride || (window.HerSpaceStore && window.HerSpaceStore.state ? window.HerSpaceStore.state.lang : 'en') || 'en';
  const dict = window.HERSPACE_I18N[lang] || window.HERSPACE_I18N.en;
  let value = dict[key];

  if (value === undefined || value === '') {
    if (window.HERSPACE_I18N.en && window.HERSPACE_I18N.en[key]) {
      value = window.HERSPACE_I18N.en[key];
    } else {
      value = key;
    }
  }

  if (vars && typeof value === 'string') {
    Object.keys(vars).forEach(function(k) {
      const regex = new RegExp('\\{' + k + '\\}', 'g');
      value = value.replace(regex, String(vars[k]));
    });
  }
  return value;
};

/**
 * Automated Translation Completeness Auditor
 * Verifies 100% key parity between English ('en') and Tamil ('ta'), checks for empty strings,
 * and validates glossary completeness.
 */
window.herSpaceTranslationAudit = function() {
  const enDict = window.HERSPACE_I18N.en || {};
  const taDict = window.HERSPACE_I18N.ta || {};
  const enKeys = Object.keys(enDict);
  const taKeys = Object.keys(taDict);

  const missingInTa = enKeys.filter(function(k) { return !(k in taDict); });
  const missingInEn = taKeys.filter(function(k) { return !(k in enDict); });
  const emptyInEn = enKeys.filter(function(k) { return typeof enDict[k] !== 'string' || enDict[k].trim() === ''; });
  const emptyInTa = taKeys.filter(function(k) { return typeof taDict[k] !== 'string' || taDict[k].trim() === ''; });

  return {
    totalEnKeys: enKeys.length,
    totalTaKeys: taKeys.length,
    glossaryCount: (window.HERSPACE_GLOSSARY || []).length,
    missingInTa: missingInTa,
    missingInEn: missingInEn,
    emptyInEn: emptyInEn,
    emptyInTa: emptyInTa,
    parityPercentage: enKeys.length > 0 ? Math.round(((enKeys.length - missingInTa.length - emptyInTa.length) / enKeys.length) * 100) : 100,
    isComplete: missingInTa.length === 0 && missingInEn.length === 0 && emptyInEn.length === 0 && emptyInTa.length === 0
  };
};
